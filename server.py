# Global variable for stitching setup
stitching_setup = None

# Basemap homography computed from the web client's map_calibration message.
# None until the web client sends calibration points, in which case tracking
# matches are sent as GeoJSON (see handle_web_client); otherwise a plain
# marker dict is sent.
basemap_homography: BasemapHomography | None = None

# How far catalog geometry must shrink to sit on top of its 1:500 block under the *current*
# calibration (physical_building_catalog.model_scale_factor). Derived from the homography the
# moment one is accepted -- never sent by the frontend, never measured by hand -- and reset to
# None alongside it, so a stale factor can never outlive the calibration it was derived from.
global_model_scale_factor: float | None = None

# The session_store id of the calibration currently in force. Generated by Python from the
# accepted handshake (the frontend has no session id and sends none), so every building
# measurement can be filed against the homography it was actually measured under.
current_session_id: str | None = None

